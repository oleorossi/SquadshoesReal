              AND p.proname NOT IN ('get_public_ready_stock','submit_public_ready_stock_inquiry','is_closed_sale_order_status')
  LOOP
    EXECUTE format('REVOKE EXECUTE ON FUNCTION %s FROM PUBLIC, anon', r.sig);
  END LOOP;
END $g$;
