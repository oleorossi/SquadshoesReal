/**
 * Falta líquida de compra.
 *
 * A reserva e o estoque físico já saem da necessidade antes da OC aberta.
 * OC comprometida (manual, MRP, automática já aprovada/enviada, tira) cobre
 * a falta que sobrou, na ordem de `sortKey` (menor primeiro). Rascunho e
 * sugestão automática `per_pv` NÃO entram: são o documento que o worker
 * reescreve. Contá-los zeraria a compra e a recriaria no ciclo seguinte.
 */

export interface NeedLine {
  saleOrderId: string;
  productId: string;
  needed: number;
  /** Empenho deste PV neste produto. Cobre a necessidade dele antes do estoque livre. */
  ownReserved: number;
  /** Menor chave atende primeiro. Semana de faturamento + criação do PV. */
  sortKey: string;
}

export interface ProductStock {
  onHand: number;
  /** Empenho total do produto, inclusive o dos PVs desta conta. */
  reserved: number;
  /** Saldo ainda não recebido em OC que já é compromisso. */
  openCommitted: number;
}

export interface NettedLine extends NeedLine {
  shortage: number;
  coveredByStock: number;
  coveredByPurchase: number;
}

const CLOSED = new Set([
  'cancelled',
  'canceled',
  'cancelada',
  'received',
  'recebida',
  'receiving',
]);

/** OC entra na cobertura da falta. Rascunho automático do PV não entra. */
export function purchaseOrderCountsAsCover(po: {
  status: string;
  autoGenerated?: boolean;
  sourceType?: string | null;
  /** OC da aba Tiras: napa que vai para o prestador e não entra no estoque da fábrica. */
  strapAtelierJob?: boolean;
}): boolean {
  if (po.strapAtelierJob) return false;
  const status = (po.status || '').trim().toLowerCase();
  if (CLOSED.has(status)) return false;
  if (
    po.autoGenerated
    && po.sourceType === 'per_pv'
    && (status === 'draft' || status === 'suggested')
  ) {
    return false;
  }
  return true;
}

/** `products.supplier_id`, senão `preferred_supplier_id`. */
export function resolvePurchaseSupplier(
  supplierId: string | null | undefined,
  preferredSupplierId: string | null | undefined,
): string | null {
  const primary = supplierId?.trim();
  if (primary) return primary;
  const fallback = preferredSupplierId?.trim();
  return fallback || null;
}

function allocatedShortage(demand: number, cover: number, priorDemand: number): number {
  const need = Math.max(0, demand || 0);
  const left = Math.max(0, (cover || 0) - Math.max(0, priorDemand || 0));
  return Math.max(0, need - left);
}

/**
 * Falta por linha. Estoque livre = físico − empenho dos outros.
 * O empenho próprio cobre o PV antes de disputar o livre.
 * A OC comprometida cobre o que o estoque não cobriu.
 */
export function netPurchaseLines(
  lines: readonly NeedLine[],
  stockByProduct: Readonly<Record<string, ProductStock>>,
): NettedLine[] {
  const byProduct = new Map<string, NeedLine[]>();
  for (const line of lines) {
    const bucket = byProduct.get(line.productId) ?? [];
    bucket.push(line);
    byProduct.set(line.productId, bucket);
  }

  const out: NettedLine[] = [];
  for (const [productId, group] of byProduct) {
    const stock = stockByProduct[productId] ?? { onHand: 0, reserved: 0, openCommitted: 0 };
    const ordered = [...group].sort((a, b) => {
      if (a.sortKey !== b.sortKey) return a.sortKey < b.sortKey ? -1 : 1;
      return a.saleOrderId < b.saleOrderId ? -1 : a.saleOrderId > b.saleOrderId ? 1 : 0;
    });

    const ownTotal = ordered.reduce((sum, line) => sum + Math.max(0, line.ownReserved), 0);
    const reservedByOthers = Math.max(0, stock.reserved - ownTotal);
    const free = Math.max(0, stock.onHand - reservedByOthers - ownTotal);

    let priorShared = 0;
    const afterStock = ordered.map((line) => {
      const ownCover = Math.min(Math.max(0, line.needed), Math.max(0, line.ownReserved));
      const shared = Math.max(0, line.needed) - ownCover;
      const shortage = allocatedShortage(shared, free, priorShared);
      const coveredByStock = Math.max(0, line.needed) - shortage;
      priorShared += shared;
      return { line, shortage, coveredByStock };
    });

    let priorShort = 0;
    for (const row of afterStock) {
      const shortage = allocatedShortage(row.shortage, stock.openCommitted, priorShort);
      priorShort += row.shortage;
      out.push({
        ...row.line,
        shortage,
        coveredByStock: row.coveredByStock,
        coveredByPurchase: row.shortage - shortage,
      });
    }
  }

  return out;
}
