import { describe, expect, it } from 'vitest';
import {
  netPurchaseLines,
  purchaseOrderCountsAsCover,
  resolvePurchaseSupplier,
} from '@/lib/purchaseShortageNet';

describe('falta líquida: reservas e OCs abertas', () => {
  it('desconta o empenho dos outros e não recompra o que o próprio PV já reservou', () => {
    const rows = netPurchaseLines(
      [
        { saleOrderId: 'pv1', productId: 'napa', needed: 80, ownReserved: 80, sortKey: '2026-11-02' },
        { saleOrderId: 'pv2', productId: 'napa', needed: 40, ownReserved: 0, sortKey: '2026-11-09' },
      ],
      { napa: { onHand: 80, reserved: 80, openCommitted: 0 } },
    );
    const byId = Object.fromEntries(rows.map((row) => [row.saleOrderId, row.shortage]));
    expect(byId.pv1).toBe(0);
    expect(byId.pv2).toBe(40);
  });

  it('divide a OC comprometida uma vez, na ordem da semana de faturamento', () => {
    const rows = netPurchaseLines(
      [
        { saleOrderId: 'pv-cedo', productId: 'napa', needed: 80, ownReserved: 0, sortKey: '2026-11-02' },
        { saleOrderId: 'pv-tarde', productId: 'napa', needed: 80, ownReserved: 0, sortKey: '2026-11-09' },
      ],
      { napa: { onHand: 30, reserved: 0, openCommitted: 40 } },
    );
    const byId = Object.fromEntries(rows.map((row) => [row.saleOrderId, row]));
    expect(byId['pv-cedo'].coveredByStock).toBe(30);
    expect(byId['pv-cedo'].coveredByPurchase).toBe(40);
    expect(byId['pv-cedo'].shortage).toBe(10);
    expect(byId['pv-tarde'].shortage).toBe(80);
  });

  it('rascunho automático não cobre; OC aprovada, manual e de tira cobrem', () => {
    expect(purchaseOrderCountsAsCover({
      status: 'draft', autoGenerated: true, sourceType: 'per_pv',
    })).toBe(false);
    expect(purchaseOrderCountsAsCover({
      status: 'suggested', autoGenerated: true, sourceType: 'per_pv',
    })).toBe(false);
    expect(purchaseOrderCountsAsCover({
      status: 'approved', autoGenerated: true, sourceType: 'per_pv',
    })).toBe(true);
    expect(purchaseOrderCountsAsCover({
      status: 'pending', autoGenerated: false, sourceType: 'manual',
    })).toBe(true);
    expect(purchaseOrderCountsAsCover({
      status: 'sent', autoGenerated: false, sourceType: 'strap_demand',
    })).toBe(true);
    expect(purchaseOrderCountsAsCover({
      status: 'received', autoGenerated: false, sourceType: 'manual',
    })).toBe(false);
    expect(purchaseOrderCountsAsCover({
      status: 'cancelled', autoGenerated: false, sourceType: 'mrp',
    })).toBe(false);
    expect(purchaseOrderCountsAsCover({
      status: 'pending', autoGenerated: false, sourceType: 'manual', strapAtelierJob: true,
    })).toBe(false);
  });

  it('fornecedor do produto, com fallback no preferencial', () => {
    expect(resolvePurchaseSupplier('forn-a', 'forn-b')).toBe('forn-a');
    expect(resolvePurchaseSupplier(null, 'forn-b')).toBe('forn-b');
    expect(resolvePurchaseSupplier('  ', null)).toBe(null);
  });
});
